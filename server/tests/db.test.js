/**
 * Database tests (MySQL required). If no local MySQL is running the whole file is skipped with a
 * reason instead of failing, so `npm test` still works on a machine without a database.
 *
 * They check the parts of the design that matter for the API: the demo data loads, the totals and the
 * generated line_total column agree with the pricing service, JSON columns round-trip, popularity is
 * derived from orders, and the constraints (unique, foreign key, check) actually reject bad rows.
 */
import test, { after } from 'node:test';
import assert from 'node:assert/strict';

process.env.NODE_ENV = 'test';

const { default: config } = await import('../src/config/env.js');
const { ping, closePools, execute, query, queryOne } = await import('../src/db/pool.js');
const { runMigration } = await import('../src/db/migrate.js');
const { seedDatabase } = await import('../src/db/seed.js');
const { calculateTotals } = await import('../src/services/pricing.js');

const uri = config.db.testUri;

let databaseAvailable = true;
try {
  // runMigration doubles as the availability probe: it creates the test schema when it is missing.
  await runMigration({ uri });
  databaseAvailable = await ping(uri);
} catch (error) {
  databaseAvailable = false;
  console.log(`Skipping database tests: ${error.message}`);
}

const options = databaseAvailable ? {} : { skip: `MySQL is not reachable at ${uri}` };

test('database', options, async (t) => {
  await t.test('migrates and seeds the test schema', async () => {
    await runMigration({ uri, fresh: true });
    const counts = await seedDatabase({ uri });

    assert.equal(counts.users, 3);
    assert.equal(counts.menu_items, 24);
    assert.equal(counts.restaurant_tables, 6);
    assert.equal(counts.orders, 6);
    assert.equal(counts.order_items, 13);
    assert.equal(counts.feedback, 3);
  });

  await t.test('an order must belong to an account or to a guest with contact details', async () => {
    await assert.rejects(
      () => execute('INSERT INTO orders (reference) VALUES (?)', ['ORD-9001'], uri),
      (error) => /Check constraint/i.test(error.message),
      'the schema refuses an order nobody can be contacted about',
    );

    const result = await execute(
      'INSERT INTO orders (reference, contact_name, contact_email, total) VALUES (?, ?, ?, 10)',
      ['ORD-9002', 'Guest', 'guest@example.com'],
      uri,
    );
    assert.ok(result.insertId > 0, 'a guest order with an email is allowed');
    await execute('DELETE FROM orders WHERE id = ?', [result.insertId], uri);

    const reservations = await query('SELECT reference, user_id, contact_email FROM reservations ORDER BY reference', [], uri);
    assert.equal(reservations.length, 4);
    assert.equal(reservations[3].contact_email, 'guest@example.com', 'the guest booking has no account but can be contacted');
  });

  await t.test('stored order totals match the pricing service', async () => {
    const order = await queryOne('SELECT * FROM orders WHERE reference = ?', ['ORD-1001'], uri);
    const lines = await query(
      'SELECT unit_price, quantity FROM order_items WHERE order_id = ?',
      [order.id],
      uri,
    );

    const expected = calculateTotals(
      lines.map((line) => ({ unitPrice: Number(line.unit_price), quantity: line.quantity })),
      order.fulfilment,
    );

    assert.equal(Number(order.subtotal), expected.subtotal);
    assert.equal(Number(order.delivery_fee), expected.deliveryFee);
    assert.equal(Number(order.tax), expected.tax);
    assert.equal(Number(order.total), expected.total);
  });

  await t.test('line_total is generated by the database, not by application code', async () => {
    const line = await queryOne(
      'SELECT unit_price, quantity, line_total FROM order_items WHERE name = ? LIMIT 1',
      ['Fresh Lemonade'],
      uri,
    );
    assert.equal(Number(line.line_total), Number(line.unit_price) * Number(line.quantity));
  });

  await t.test('JSON columns round-trip as arrays', async () => {
    const item = await queryOne('SELECT ingredients, allergens, dietary_tags FROM menu_items WHERE name = ?', ['Crispy Calamari'], uri);
    assert.ok(Array.isArray(item.ingredients));
    assert.ok(item.allergens.includes('shellfish'));
    assert.ok(item.dietary_tags.includes('dairy-free'));
  });

  await t.test('menu popularity is derived from the seeded orders', async () => {
    const popular = await queryOne('SELECT name, popularity FROM menu_items ORDER BY popularity DESC, name LIMIT 1', [], uri);
    assert.equal(popular.name, 'Margherita Pizza');
    assert.equal(Number(popular.popularity), 3);

    const cancelledOnly = await queryOne(
      `SELECT mi.popularity FROM menu_items mi JOIN order_items oi ON oi.menu_item_id = mi.id
        JOIN orders o ON o.id = oi.order_id
       WHERE mi.name = 'Classic Beef Burger & Fries' AND o.status = 'cancelled' LIMIT 1`,
      [],
      uri,
    );
    assert.equal(Number(cancelledOnly.popularity), 0, 'cancelled orders must not count as popularity');
  });

  await t.test('DATE and TIME columns serialise as strings (no timezone drift)', async () => {
    const reservation = await queryOne('SELECT reservation_date, start_time, end_time FROM reservations WHERE reference = ?', ['RES-5002'], uri);
    assert.match(reservation.reservation_date, /^\d{4}-\d{2}-\d{2}$/);
    assert.equal(reservation.start_time, '18:30:00');
    assert.equal(reservation.end_time, '21:30:00');
  });

  await t.test('unique constraints reject duplicates', async () => {
    await assert.rejects(
      () => execute('INSERT INTO users (name, email, password_hash) VALUES (?, ?, ?)', ['Copy', 'demo@srms.dev', 'hash'], uri),
      (error) => error.code === 'ER_DUP_ENTRY',
    );
    await assert.rejects(
      () => execute('INSERT INTO menu_items (name, category, price) VALUES (?, ?, ?)', ['Garden Salad', 'starter', 5], uri),
      (error) => error.code === 'ER_DUP_ENTRY',
    );
  });

  await t.test('check constraints reject invalid values', async () => {
    await assert.rejects(
      () => execute('INSERT INTO menu_items (name, category, price) VALUES (?, ?, ?)', ['Free Stuff', 'starter', 0], uri),
      (error) => error.code === 'ER_CHECK_CONSTRAINT_VIOLATED' || /Check constraint/i.test(error.message),
    );

    const order = await queryOne('SELECT id FROM orders LIMIT 1', [], uri);
    await assert.rejects(
      () => execute('INSERT INTO order_items (order_id, name, unit_price, quantity) VALUES (?, ?, ?, ?)', [order.id, 'Zero items', 5, 0], uri),
      (error) => /Check constraint/i.test(error.message),
    );
  });

  await t.test('foreign keys reject an orphan order line', async () => {
    await assert.rejects(
      () => execute('INSERT INTO order_items (order_id, name, unit_price, quantity) VALUES (?, ?, ?, ?)', [999999, 'Ghost line', 5, 1], uri),
      (error) => error.code === 'ER_NO_REFERENCED_ROW_2' || /foreign key/i.test(error.message),
    );
  });
});

after(async () => {
  await closePools();
});
